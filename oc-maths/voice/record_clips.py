# Pre-record the app's cheer lines with a neural voice, nudged up to a child's pitch.
import sys,os,re,json,subprocess,tempfile
import numpy as np,soundfile as sf
from kokoro_onnx import Kokoro
models,appdir=sys.argv[1],sys.argv[2]
out=os.path.join(appdir,'voice');os.makedirs(out,exist_ok=True)
k=Kokoro(models+'/kokoro-v1.0.onnx',models+'/voices-v1.0.bin')
style=k.get_voice_style('af_heart')*0.7+k.get_voice_style('af_sky')*0.3
NAMES={'a':'mˈɪtʰɪlɑː','b':'mˈɪθɪlɑː'}   # a: Indian-style "MIT-hi-laa", b: English-style "MITH-i-laa"
LINES={
 'correct':['Yes!','Awesome!','Great job, {N}!','You got it!','Brilliant!','Woohoo!','Nailed it!','Super job!','Yay, {N}!','That is right!'],
 'after':['You got there!','Never give up! Yay!','Well done for trying again!','Yes! You worked it out, {N}!'],
 'streak3':['Three in a row!','Hat trick! Woohoo!','Three in a row, {N}! So cool!'],
 'streak5':['Five in a row! You are on fire!','Five in a row! Unstoppable!','Wow! Five in a row, {N}!'],
 'levelup':['Level up! Yay!','Woohoo! You levelled up!','Level up, {N}! You are getting so smart!'],
 'goal':['Yay! Daily goal complete!','You did it! Daily goal smashed!','Hooray! Daily goal done, {N}!'],
 'round':['Round complete! Great job!','Yay! You finished the round, {N}!'],
 'test':['Wow! What a score!','Amazing test, {N}! Hooray!'],
 'best':['New best score! Woohoo!','A new record! Yay!'],
 'buy':['Ooh! Looking good!','So fancy! Yay!','I love it!'],
 'sample':["Hi {N}! I am your cheer buddy. Let's go!"],
}
src=open(os.path.join(appdir,'rewards.js'),encoding='utf-8').read()
for bid,bname in re.findall(r"\{id:'(\w+)',name:'([^']+)',glyph",src):LINES['badge_'+bid]=[f'Woohoo! You unlocked the {bname} badge!']
for tid,tname in re.findall(r"\{id:'(\w+)',name:'([^']+)',min:(?!0)",src):LINES['tier_'+tid]=['Amazing, {N}! You reached '+tname+' tier!']
def phon(text,nm):
    parts=text.split('{N}');ph=[]
    for i,p in enumerate(parts):
        if p.strip():ph.append(k.tokenizer.phonemize(p,'en-us'))
        if i<len(parts)-1:ph.append(nm)
    s=' '.join(x.strip() for x in ph if x is not None)
    return re.sub(r'\s+([,!.?])',r'\1',s)
def noname(t):return re.sub(r'\s*,?\s*\{N\}','',t).replace(' !','!').replace('Hi!','Hi!')
def render(text,dest,nm=None):
    if nm:samples,sr=k.create(phon(text,nm),voice=style,speed=0.96,is_phonemes=True)
    else:samples,sr=k.create(text,voice=style,speed=0.96,lang='en-us')
    with tempfile.NamedTemporaryFile(suffix='.wav',delete=False) as f:sf.write(f.name,samples,sr);tmp=f.name
    # +2.6 semitones with formants raised too (a child's shorter vocal tract), tempo kept; gentle polish and loudness.
    af=f'asetrate={sr}*1.16,aresample=44100,atempo=0.862,highpass=f=120,equalizer=f=3500:t=q:w=1.2:g=2,loudnorm=I=-16:TP=-1.5:LRA=11,adelay=40'
    subprocess.run(['ffmpeg','-y','-loglevel','error','-i',tmp,'-af',af,'-ac','1','-ar','44100','-codec:a','libmp3lame','-b:a','64k',dest],check=True);os.unlink(tmp)
manifest={}
for kind,lines in LINES.items():
    manifest[kind]=[]
    for i,t in enumerate(lines):
        base=f'{kind}_{i}';hasN='{N}' in t
        if hasN:
            for v,nm in NAMES.items():render(t,os.path.join(out,f'{base}_{v}.mp3'),nm)
            render(noname(t),os.path.join(out,f'{base}_x.mp3'))
        else:render(t,os.path.join(out,f'{base}.mp3'))
        manifest[kind].append({'id':base,'name':hasN,'text':t})
    print(kind,len(lines),flush=True)
open(os.path.join(out,'clips.js'),'w').write('// Generated by the voice recording script: which pre-recorded cheer clips exist for each moment.\nconst VCLIPS='+json.dumps(manifest,ensure_ascii=False)+';\n')
